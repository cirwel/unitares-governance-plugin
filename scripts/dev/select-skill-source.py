#!/usr/bin/env python3
"""Select and prove the canonical snapshot for CI's committed skill bundle.

Unchanged bundles use the source recorded by their last landed mirror. Changed
bundles must match current canonical master. Neither path alters freshness
rules, and privileged mirror delivery still verifies current canonical master.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys

SHA = re.compile(r"[0-9a-f]{40}")
PROVENANCE = re.compile(r"^Verified byte mirror of cirwel/unitares at ([0-9a-f]{40})\.$", re.M)
MANIFEST = "SKILLS_MANIFEST.sha256"
HEADER = (
    "# Canonical fingerprint of unitares/skills/ — generated by\n"
    "# scripts/dev/skills_manifest.py. Do not hand-edit; run the script.\n"
    "# Consumers (e.g. the plugin mirror) verify their copy against this file.\n"
)


class InvalidBundle(ValueError):
    """The candidate cannot be tied to an eligible canonical snapshot."""


def git(root: Path, *args: str) -> bytes:
    result = subprocess.run(["git", "-C", str(root), *args], capture_output=True)
    if result.returncode:
        raise InvalidBundle("Git provenance lookup failed; fetch complete histories")
    return result.stdout


def ancestor(root: Path, older: str, newer: str) -> bool:
    result = subprocess.run(
        ["git", "-C", str(root), "merge-base", "--is-ancestor", older, newer],
        capture_output=True,
    )
    if result.returncode not in (0, 1):
        raise InvalidBundle("Cannot establish provenance ancestry")
    return result.returncode == 0


def tree(root: Path, revision: str) -> dict[str, tuple[str, str]]:
    entries = {}
    for record in git(root, "ls-tree", "-r", "-z", f"{revision}:skills").split(b"\0"):
        if not record:
            continue
        metadata, raw_name = record.split(b"\t", 1)
        mode, kind, oid = metadata.decode("ascii").split()
        if kind != "blob" or mode not in ("100644", "100755"):
            raise InvalidBundle("Skills contain a symlink or non-file entry")
        entries[raw_name.decode("utf-8")] = (mode, oid)
    if not entries:
        raise InvalidBundle("Skills tree is empty")
    return entries


def select_source(plugin: Path, canonical: Path, base: str) -> str:
    if not SHA.fullmatch(base) or base == "0" * 40:
        raise InvalidBundle("A full, nonzero trusted event base SHA is required")
    head = git(plugin, "rev-parse", "HEAD").decode().strip()
    if not ancestor(plugin, base, head):
        raise InvalidBundle("Event base is not an ancestor of the candidate")
    landed = git(plugin, "rev-parse", "refs/remotes/origin/master^{commit}").decode().strip()
    if not ancestor(plugin, base, landed):
        raise InvalidBundle("Event base is not on plugin master ancestry")
    current = git(canonical, "rev-parse", "refs/remotes/origin/master^{commit}").decode().strip()
    candidate = tree(plugin, head)
    if candidate == tree(plugin, base):
        # Read only landed first-parent history, never a PR-authored message.
        message = git(plugin, "log", "--first-parent", "-1", "--format=%B", base, "--", "skills").decode()
        matches = PROVENANCE.findall(message)
        if len(matches) != 1:
            raise InvalidBundle("Last landed skills change lacks unique verified-mirror provenance")
        source = matches[0]
        if not ancestor(canonical, source, current):
            raise InvalidBundle("Recorded source is not on canonical master ancestry")
    else:
        source = current
    expected = tree(canonical, source)
    expected.pop(MANIFEST, None)
    manifest = candidate.pop(MANIFEST, None)
    if candidate != expected:
        raise InvalidBundle("Skills differ from the selected canonical snapshot (including attestations and modes)")
    if manifest is None or manifest[0] != "100644":
        raise InvalidBundle("Canonical manifest is missing or executable")
    lines = []
    for name, (_, oid) in sorted(expected.items()):
        if Path(name).name == MANIFEST or ".attestations" in Path(name).parts:
            continue
        digest = hashlib.sha256(git(canonical, "cat-file", "blob", oid)).hexdigest()
        lines.append(f"{digest}  {name}")
    body = "\n".join(lines)
    aggregate = hashlib.sha256(body.encode()).hexdigest()
    proof = f"{HEADER}# aggregate: {aggregate}\n{body}\n".encode()
    if git(plugin, "cat-file", "blob", manifest[1]) != proof:
        raise InvalidBundle("Manifest differs from independently computed canonical content")
    return source


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plugin-root", type=Path, required=True)
    parser.add_argument("--canonical-root", type=Path, required=True)
    parser.add_argument("--base", required=True)
    args = parser.parse_args()
    try:
        print(select_source(args.plugin_root, args.canonical_root, args.base))
    except (InvalidBundle, UnicodeError, OSError) as error:
        print(f"Skill source proof failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
